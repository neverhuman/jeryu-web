// Preserve real alpha while exporting the shared public-page dragon scene.
import { stdout } from 'node:process';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const master = resolve(web, 'design/landing-v6/dragon-graphic-master.png');
const output = resolve(web, 'src/pages/boot/landing/v6');
const identify = (format, path) => execFileSync('identify', ['-format', format, path], { encoding: 'utf8' }).trim();
const hash = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');
const [width, height] = identify('%w %h', master).split(' ').map(Number);
if (identify('%[opaque]', master).toLowerCase() !== 'false') throw new Error('Scene master must contain transparency.');
mkdirSync(output, { recursive: true });
const widths = [...new Set([320, 640, 960, width].filter((size) => size <= width))].sort((a, b) => a - b);
const exports = [];
const imports = [];
const sources = [];
for (const size of widths) {
  const filename = `dragon-graphic-${size}.webp`;
  const destination = resolve(output, filename);
  execFileSync('convert', [master, '-strip', '-colorspace', 'sRGB', '-resize', `${size}x`, '-quality', '84', '-define', 'webp:method=6', '-define', 'webp:alpha-quality=100', destination]);
  if (identify('%[opaque]', destination).toLowerCase() !== 'false') throw new Error(`Alpha lost in ${filename}`);
  exports.push({ filename, width: size, height: Number(identify('%h', destination)), alpha: true, bytes: statSync(destination).size, sha256: hash(destination) });
  imports.push(`import scene${size} from './${filename}';`);
  sources.push('${' + `scene${size}} ${size}w`);
}
const defaultSize = widths.includes(960) ? 960 : widths.at(-1);
const manifest = {
  generator: 'node apps/web/scripts/export-landing-graphic-scene.mjs',
  converter: execFileSync('convert', ['-version'], { encoding: 'utf8' }).split('\n')[0],
  quality: 84, alpha_quality: 100,
  master: 'apps/web/design/landing-v6/dragon-graphic-master.png',
  master_sha256: hash(master), width, height, alpha: true,
  crop: 'Complete transparent portrait; no crop; no baked grid or background', exports,
};
writeFileSync(resolve(output, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
writeFileSync(resolve(output, 'sceneAssets.ts'), `// Generated by export-landing-graphic-scene.mjs. Do not hand edit.\n${imports.join('\n')}\n\nexport const dragonScene = { src: scene${defaultSize}, srcSet: \`${sources.join(', ')}\`, width: ${width}, height: ${height} } as const;\n`);
stdout.write(`${JSON.stringify(manifest, null, 2)}\n`);
